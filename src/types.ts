/**
 * Core type definitions for Strudel AI Live Studio.
 * Includes data models for presets, audio synthesis telemetry, AI prompt contracts,
 * AST parser tokens, and studio control state.
 */

/**
 * Represents a curated or user-saved track preset in the studio.
 */
export interface TrackPreset {
  /** Unique identifier for the preset */
  id: string;
  /** Display title */
  title: string;
  /** Musical genre (e.g. Cyberpunk, Lo-Fi, Ambient, UK Garage, Techno) */
  genre: string;
  /** Default tempo in Beats Per Minute */
  bpm: number;
  /** Difficulty/Complexity classification tier */
  complexity: 'Beginner' | 'Intermediate' | 'Advanced';
  /** Runnable Strudel live-coding JavaScript code */
  code: string;
  /** High-level description of the sonic characteristics and arrangement */
  description: string;
  /** Search and filtering tags */
  tags: string[];
  /** Optional musical theory notes explaining chords, scale, or rhythmic meter */
  theoryNotes?: string;
}

/**
 * Real-time event emitted when a musical note or drum hit is triggered by the audio engine.
 * Used to power visualizers (oscilloscope, radar, spectrum, and voice meters).
 */
export interface TriggeredNote {
  /** Unique transient note event ID */
  id: string;
  /** AudioContext clock timestamp */
  timestamp: number;
  /** Voice classification channel */
  voice: 'drums' | 'bass' | 'chords' | 'lead' | 'fx';
  /** Human-readable note or sample label (e.g., 'bd', 'sd', 'c3', 'f#4') */
  label: string;
  /** Dynamic velocity / gain scalar (0.0 - 1.0) */
  velocity: number;
  /** Optional frequency or pitch in Hz / MIDI number */
  pitch?: number;
  /** Step position in the active 16-step rhythmic cycle */
  step?: number;
}

/**
 * Reference entry in the TidalCycles / Strudel mini-notation cheatsheet guide.
 */
export interface NotationSymbol {
  /** Syntax character or operator (e.g. `(k,n)`, `*`, `/`, `< >`, `[ ]`, `?`) */
  symbol: string;
  /** Descriptive name of the notation feature */
  title: string;
  /** Functional category */
  category: 'Rhythm' | 'Grouping' | 'Speed' | 'Variation' | 'Effects';
  /** Formal syntax format description */
  syntax: string;
  /** Concrete code snippet illustrating usage */
  example: string;
  /** Detailed plain-English explanation of how the operator behaves */
  description: string;
  /** Optional mini audio snippet to test in the engine */
  audioExampleSnippet?: string;
}

/**
 * Structured response contract returned from AI code synthesis endpoints.
 */
export interface AIGeneratedTrack {
  /** Runnable Strudel live-coding code block */
  code: string;
  /** Track title generated by AI */
  title: string;
  /** Recommended BPM */
  bpm: number;
  /** Musical genre classification */
  genre: string;
  /** High-level explanation of the track structure and sonic layers */
  explanation: string;
  /** Breakdown of key mini-notation symbols used in the generated code */
  notationBreakdown: Array<{
    symbolOrMethod: string;
    meaning: string;
  }>;
  /** Suggested immediate hand-tweaks and performance variation snippets */
  liveTweaks: Array<{
    label: string;
    code: string;
    description?: string;
  }>;
}

/**
 * Result returned when asking the AI to tweak an existing track pattern.
 */
export interface AITweakResult {
  /** Updated runnable Strudel code */
  code: string;
  /** Explanation of what was modified */
  summary: string;
  /** List of key diffs and parameter changes */
  diffHighlights: string[];
  /** Secondary follow-up tweak options */
  liveTweaks: Array<{
    label: string;
    code: string;
  }>;
}

/**
 * Result of line-by-line musical analysis and educational explanation.
 */
export interface AIExplanationResult {
  /** General summary of the musical composition */
  summary: string;
  /** Detailed line-by-line role breakdown */
  lineByLine: Array<{
    line: string;
    role: 'Drums' | 'Bass' | 'Harmony' | 'Melody' | 'FX' | 'Structure';
    explanation: string;
  }>;
  /** Contextual mini-notation guide entries applicable to this code */
  miniNotationGuide: Array<{
    symbol: string;
    title: string;
    explanation: string;
    example: string;
  }>;
  /** Music theory insights (e.g. modal scales, chord inversions, syncopation) */
  musicTheoryTip: string;
}

/**
 * Curated algorithmic variation transformation (e.g., Drop, Breakdown, Euclidean Shift).
 */
export interface AIVariation {
  /** Optional unique identifier for tracking */
  id?: string;
  /** Display title */
  title: string;
  /** Variation category */
  type: 'drop' | 'breakdown' | 'polyrhythm' | 'harmonic' | 'glitch' | 'chill' | string;
  /** Explanation of the musical transformation */
  description: string;
  /** Transformed runnable Strudel code */
  code: string;
  /** Timestamp when created */
  createdAt?: number;
}

/**
 * Saved algorithmic live-coding session snapshot with custom variations, tempo, and metadata.
 */
export interface SavedSession {
  /** Unique session ID */
  id: string;
  /** User-assigned or generated name */
  name: string;
  /** Primary runnable Strudel code pattern */
  code: string;
  /** Target tempo in BPM */
  bpm: number;
  /** Musical genre classification */
  genre: string;
  /** Search and filtering tags */
  tags: string[];
  /** Optional detailed notes / description */
  description?: string;
  /** Array of saved performance variations and DJ transitions */
  variations: AIVariation[];
  /** Creation timestamp (Unix ms) */
  createdAt: number;
  /** Last updated timestamp (Unix ms) */
  updatedAt: number;
}

/**
 * Global reactive state model for the Web Audio synthesis engine.
 */
export interface AudioEngineState {
  /** Whether the audio scheduler and transport are running */
  isPlaying: boolean;
  /** Active tempo in BPM */
  bpm: number;
  /** Monotonically increasing cycle sequence count */
  cycle: number;
  /** Master output gain level (0.0 - 1.0) */
  masterVolume: number;
  /** Master lowpass filter cutoff frequency in Hz */
  cutoffHz: number;
  /** Master algorithmic convolution reverb send amount (0.0 - 1.0) */
  reverbAmount: number;
  /** Master stereo feedback delay send amount (0.0 - 1.0) */
  delayAmount: number;
  /** Real-time voice pulse activity map */
  activeVoices: Record<string, number>;
  /** Any active syntax or audio playback error message */
  errorMessage: string | null;
}

/**
 * Supported client-side and cloud AI execution backends.
 */
export type AIEngineType = 'webgpu-gemma' | 'chrome-builtin' | 'instant-heuristic' | 'cloud-gemini';

/**
 * Status of local on-device neural network weights loading / compilation.
 */
export type ModelLoadingStatus = 'idle' | 'checking' | 'downloading' | 'ready' | 'error' | 'unsupported';

/**
 * Progress updates during WebGPU model download and shader compilation.
 */
export interface AIEngineProgress {
  status: ModelLoadingStatus;
  text: string;
  progress: number; // 0 to 1
  loadedBytes?: number;
  totalBytes?: number;
  timeElapsed?: number;
  errorMessage?: string;
  /**
   * Device-specific advisories (VRAM too small, no shader-f16, metered
   * connection, low storage...). Surfaced verbatim in the engine picker.
   */
  warnings?: string[];
}

/**
 * Human-readable label for each engine. Used anywhere the UI needs to name
 * the engine that actually produced a result, so no screen can claim an
 * engine that did not run.
 */
export const AI_ENGINE_LABELS: Record<AIEngineType, string> = {
  'webgpu-gemma': 'Local model (WebGPU)',
  'chrome-builtin': 'Chrome built-in AI',
  'instant-heuristic': 'Built-in pattern rules',
  'cloud-gemini': 'Gemini (your API key)',
};

/**
 * Every AI call returns its payload wrapped with the engine that ACTUALLY
 * produced it.
 *
 * This exists because the previous design caught every failure and returned
 * rule-based output under the selected engine's name, which made it
 * impossible to tell a working engine from a broken one. If a call falls back,
 * `producedBy` names the engine that really ran and `degraded` explains why
 * the requested one did not.
 */
export interface AIEngineResult<T> {
  data: T;
  /** The engine that actually generated `data`. */
  producedBy: AIEngineType;
  /** The engine the user had selected, when it differs from `producedBy`. */
  requestedEngine?: AIEngineType;
  /** Why the requested engine did not run. Present iff a fallback occurred. */
  degraded?: string;
}

/**
 * AI Worker Request payload types.
 */
export interface AIWorkerRequest {
  id: string;
  type: 'init' | 'generate' | 'tweak' | 'explain' | 'suggest_variations' | 'fix' | 'unload';
  modelId?: string;
  payload?: any;
}

/**
 * AI Worker Response payload types.
 */
export interface AIWorkerResponse {
  id: string;
  type: 'progress' | 'ready' | 'result' | 'stream_token' | 'error' | 'log';
  progress?: AIEngineProgress;
  data?: any;
  error?: string;
  /**
   * Set on 'ready' / 'progress' messages emitted while satisfying a request
   * whose own id is `id`. The main thread must NOT resolve the pending
   * request on these — loading the model is a step on the way to the answer,
   * not the answer.
   */
  phase?: 'init';
}

/**
 * Broad device class used to decide which local models to offer, recommend,
 * or hide. Derived from a real `navigator.gpu.requestAdapter()` probe rather
 * than the presence of `navigator.gpu`, which is true even on devices whose
 * adapter request returns null.
 */
export type DeviceTier =
  | 'no-webgpu'      // navigator.gpu absent entirely
  | 'no-adapter'     // navigator.gpu present but requestAdapter() returned null
  | 'mobile-low'     // phone/tablet, or very little reported memory
  | 'desktop-mid'    // works, but not enough headroom for the 2B models
  | 'desktop-high';  // comfortably runs the largest offered model

/**
 * Result of the one-time hardware probe.
 */
export interface DeviceProfile {
  tier: DeviceTier;
  /** WebGPU 'shader-f16' feature. Every q4f16_1 model needs it. */
  hasF16: boolean;
  /** adapter.limits.maxBufferSize — spec floor is 268435456 (256 MiB). */
  maxBufferSize: number;
  /** adapter.limits.maxStorageBufferBindingSize — spec floor 134217728. */
  maxStorageBufferBindingSize: number;
  /** adapter.info.vendor when exposed, e.g. 'qualcomm' | 'apple' | 'nvidia'. */
  gpuVendor: string;
  /** navigator.deviceMemory in GiB. Chromium-only; null elsewhere. */
  deviceMemoryGiB: number | null;
  hardwareConcurrency: number | null;
  /** Free bytes from navigator.storage.estimate(), best effort. */
  storageFreeBytes: number | null;
  /** saveData, or a 2g/3g effectiveType. Chromium-only; false elsewhere. */
  isMetered: boolean;
  isMobile: boolean;
  isIOS: boolean;
  isAndroid: boolean;
}

